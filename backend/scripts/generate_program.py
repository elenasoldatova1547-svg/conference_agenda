def generate() -> dict:
    """Генерирует и возвращает структуру program.json."""
    days_meta = [
        {"day": 1, "lunch_start": "13:00", "lunch_end": "14:00"},
        {"day": 2, "lunch_start": "13:00", "lunch_end": "14:00"},
    ]

    talks: list[dict] = []
    for idx, row in enumerate(RAW, start=1):
        day, widx, room, track, fmt, level, lang, title, speaker, company, tags, desc = row
        start, end = WINDOWS[widx]
        talks.append({
            "id": f"talk_{100 + idx}",
            "title": title,
            "speaker": speaker,
            "company": company,
            "track": track,
            "day": day,
            "start": start,
            "end": end,
            "room": room,
            "format": fmt,
            "language": lang,
            "level": level,
            "tags": tags,
            "description_short": desc,
        })

    return {"days": days_meta, "talks": talks}


def main() -> None:
    data = generate()
    out = Path(__file__).resolve().parent.parent / "app" / "data" / "program.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"✓ program.json written → {out}  ({len(data['talks'])} докладов)")


if __name__ == "__main__":
    main()
